// Deterministic draft evidence only. Fixed keys/nonces MUST NOT be used in assets.
// The native OpenSSL AES-KW provider is independent of the runner's ECB unwrap.
import crypto from 'node:crypto';
import fs from 'node:fs';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { argon2id } = require('@noble/hashes/argon2.js');
const b64 = bytes => Buffer.from(bytes).toString('base64');
const kwIv = Buffer.from('a6a6a6a6a6a6a6a6', 'hex');
function vector(number, mixed) {
  const id = `envelope-aead-vector-0${number}-${mixed ? 'mixed' : 'scrypt'}-multi-slot`;
  const cek = Buffer.alloc(32, 0x40 + number);
  const iv = Buffer.alloc(12, 0x60 + number);
  const plaintext = `KDNA ${id}: one CEK, independently wrapped slots.`;
  const aad = ['kdna.envelope.aead', '0.1.0',
    `urn:uuid:00000000-0000-4000-8000-00000000000${number}`,
    `kdna:fixture:multislot-${number}`, '1.0.0', 'payload.kdnab', 'licensed', 'password'].join('\n');
  const credentials = [`vector-${number}-primary`, `vector-${number}-recovery`];
  const keks = [];
  const key_slots = credentials.map((password, i) => {
    const salt = Buffer.alloc(16, number * 16 + i);
    const useArgon = mixed && i === 0;
    const kdf_profile = useArgon ? 'argon2id' : 'scrypt-sha256';
    const params = useArgon ? {t:3,m:65536,p:4,dkLen:32} : {N:32768,r:8,p:1};
    const kek = Buffer.from(useArgon
      ? argon2id(Buffer.from(password), salt, params)
      : crypto.scryptSync(password, salt, 32, {...params,maxmem:64*1024*1024}));
    keks.push(b64(kek));
    const wrap = crypto.createCipheriv('id-aes256-wrap', kek, kwIv);
    const wrapped = Buffer.concat([wrap.update(cek), wrap.final()]);
    return {slot:i===0?'password':'recovery',kdf_profile,
      kdf_params:{...params,salt:b64(salt)},wrap:'AES-256-KW',wrapped_key:b64(wrapped)};
  });
  const cipher = crypto.createCipheriv('aes-256-gcm',cek,iv);
  cipher.setAAD(Buffer.from(aad));
  const ciphertext = Buffer.concat([cipher.update(plaintext,'utf8'),cipher.final()]);
  return {id, description: mixed
    ? 'Argon2id primary and explicit scrypt recovery slot independently wrap the same CEK. Unsupported primary rejects; it never auto-selects recovery.'
    : 'Two different scrypt KEKs independently wrap one CEK; either explicitly selected slot decrypts the same plaintext.',
    inputs:{cek:b64(cek),plaintext,aad,credentials},
    expected:{keks,envelope:{profile:'kdna.envelope.aead',profile_version:'0.1.0',
      alg:'AES-256-GCM',key_wrapping:'AES-256-KW',kdf_profile:key_slots[0].kdf_profile,
      key_slots,iv:b64(iv),tag:b64(cipher.getAuthTag()),ciphertext:b64(ciphertext)}}};
}
const check = process.argv.includes('--check');
if (process.argv.slice(2).some(arg => arg !== '--check')) throw new Error('unknown argument');
for (const v of [vector(4,false),vector(5,true)]) {
  const url = new URL(`${v.id}.json`,import.meta.url);
  const bytes = JSON.stringify(v,null,2)+'\n';
  if (check) {
    if (fs.readFileSync(url,'utf8') !== bytes) throw new Error(`${v.id}: generated bytes differ`);
  } else fs.writeFileSync(url,bytes);
  console.log(`${check?'MATCH':'WROTE'} ${v.id}`);
}
